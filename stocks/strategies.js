/* القرار كلُّه هنا: يأخذ جهةَ `side` وحالةَ الدورة السابقة وختمَ
   الشمعة، ويعيد الجهةَ المنشورة والحالةَ التالية. دالّةٌ خالصة —
   تُختبر بمدخلاتٍ اصطناعية بلا سوقٍ ولا شبكة. */
function dirHold(d, H, bar, need) {
  need = Number.isFinite(need) ? need : DIR_HOLD;
  H = H || {};
  var ld = Number.isFinite(H.ld) ? H.ld : 0;
  /* بلا مرساة فلا انقلاب: أوّل جهةٍ تُنشر فوراً. وكذلك الموافقة
     والسكون — والمرساة تبقى في الحالتين. */
  if (!ld || !d || d === ld)
    return { dir: d, hold: { ld: d || ld, pd: 0, pn: 0, pb: 0 }, pend: null };

  var same = H.pd === d;
  /* **بلا ختمِ شمعةٍ لا إمساك.** العدّ بالشمعات المتمايزة، فختمٌ غير
     معروف يعني عدّاداً لا يتقدّم أبداً — والاتجاه يبقى مُمسَكاً إلى
     الأبد، وهو أسوأ من الانقلاب الذي بُنيت الآلية لمنعه. فحين يتعذّر
     القياس تُنشر جهةُ `side` كما كانت قبل الآلية. */
  if (!Number.isFinite(bar))
    return { dir: d, hold: { ld: d, pd: 0, pn: 0, pb: 0 }, pend: null };
  var newBar = Number.isFinite(bar) && Number.isFinite(H.pb) && bar > H.pb;
  var pn = same ? (newBar ? (H.pn || 0) + 1 : (H.pn || 1)) : 1;
  var pb = Number.isFinite(bar) ? Math.max(bar, H.pb || 0) : (H.pb || 0);

  if (pn >= need) return { dir: d, hold: { ld: d, pd: 0, pn: 0, pb: 0 }, pend: null };
  /* لم يصمد بعد — تُنشر الجهةُ السابقة ويُعلَن التربّص صراحةً.
     إخفاؤه يجعل الشاشة تكتم انقلاباً جارياً، وهو معلومةٌ لا ضجيج. */
  return { dir: ld, hold: { ld: ld, pd: d, pn: pn, pb: pb },
           pend: { d: d, n: pn, of: need } };
}


function sBandOf(sc) {
  if (!Number.isFinite(sc)) return null;
  var n = 0;
  for (var i = 0; i < S_BANDS.length; i++) if (sc >= S_BANDS[i]) n++;
  return n;                                                   // 0..3
}
function sBandStable(sc, prev) {
  var now = sBandOf(sc);
  if (now === null) return null;
  if (!Number.isFinite(prev) || prev < 0 || prev > 3) return now;
  var b = prev;
  while (b < 3 && sc >= S_BANDS[b] + S_MARGIN) b++;
  while (b > 0 && sc <= S_BANDS[b - 1] - S_MARGIN) b--;
  return b;
}

/* ---------------------------------------------------------------------
   أدوات البوابات — كلُّها تحترم المنطقة الميتة.

   `cmp` هي `cmp` نفسها في `score.js` بمخرَجٍ ‎−1/0/+1‎ بدل وزنٍ موقَّع:
   فرقٌ أصغر من ‎0.15×ATR‎ لا يصوّت لأيّ جهة. وبلا هذا تنقلب البوابة
   من حركةٍ لا يراها أحد — وهي العلّة المقيسة التي جعلت أبل تتذبذب
   ‎95 → 60 → 98‎ في عشرين دقيقة.
   --------------------------------------------------------------------- */
function tolOf(atr) { return (Number.isFinite(atr) && atr > 0) ? atr * DEAD_ATR : 0; }

function cmp(a, b, atr) {
  if (!Number.isFinite(a) || !Number.isFinite(b)) return null;   // غائبة لا محايدة
  var d = a - b, t = tolOf(atr);
  return Math.abs(d) <= t ? 0 : (d > 0 ? 1 : -1);
}
/* بوابةٌ موقَّعة باتجاه الاستراتيجية: تؤيّد حين يوافق الفرقُ الجهة. */
function cmpD(a, b, atr, d) { var v = cmp(a, b, atr); return v === null ? null : v * d; }

/* هل يوافق رقمٌ ذو إشارة (نتيجة فريم مثلاً) اتجاهَ الاستراتيجية؟
   `flat` منطقةُ حيادٍ صريحة — نتيجةٌ قرب الصفر لا تؤيّد ولا تناقض. */
function agree(v, d, flat) {
  if (!Number.isFinite(v)) return null;
  flat = flat || 0;
  if (Math.abs(v) <= flat) return 0;
  return (v > 0 ? 1 : -1) === d ? 1 : -1;
}
/* بوابةُ نطاق: ‎+1‎ داخل المدى المفضَّل، ‎−1‎ خارجه، ‎0‎ على حافّته. */
function inRange(v, lo, hi) {
  if (!Number.isFinite(v)) return null;
  if (v >= lo && v <= hi) return 1;
  var m = (hi - lo) * 0.25;
  if (v >= lo - m && v <= hi + m) return 0;
  return -1;
}
