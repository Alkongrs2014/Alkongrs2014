/* =====================================================================
   اتجاه الفرصة — مصدرٌ واحد يقرأه المتصفح والخادم معاً.

   لماذا ملفّ مستقلّ: الاتجاه كان يُشتقّ في ثلاثة مواضع بثلاث طرق —
   `planDirOf` في `plan.js` من النتيجة، و`oppDirOf` في `index.html`
   بأوّل شرطٍ مفروض، و`track-signals` لكلّ شرطٍ على حدة. فسهمٌ واحد
   يُطلق شرطين متعاكسين يخرج باتجاهين: `AVGO` أطلقت `alignDn` (▼) و
   `divBull` (▲ مفروض) معاً، فظهرت الفرصة «صعود» والقراءة الفنية
   ‎−68.8‎ وكلُّ فريماتها الأربعة هابطة. وهي نفس علّة `plan.js` و
   `scans.js` ونفس حلّها: نسخة واحدة لا ثلاث.

   الملفّ **نقيّ**: أرقام تدخل وأرقام تخرج، بلا `state` ولا DOM ولا
   قراءة ملفات ولا استيراد تعريفات الشروط — المستهلك يمرّر `forced`
   رقماً كما يفعل مع `planFrom`.
   ===================================================================== */

/* حدّ الاتجاه: ما تحت ‎−15‎ هبوط وما فوقه صعود — نفس حدّ `planDirOf`
   و`labelOf` بالحرف، لا رقمٌ جديد. */
var DIR_CUT = -15;

/* =====================================================================
   الاتجاه الأساس — من **النطاق المثبَّت** لا من النتيجة الخام.

   وهذا هو موضع الثبات كلّه: `bandStable` تمنع تغيّر النطاق إلا بتجاوز
   حدّه بـ‎3‎ نقاط، والخادم وحده يحسبها لأنه وحده يملك الدورة السابقة.
   فاشتقاقُ الاتجاه منه يورّثه الهيستريسس **بلا آليةٍ جديدة** — ورقمٌ
   يستقرّ على الحدّ لا يعود يقلب الفرصة من صعود إلى هبوط كلّ دورة.

   والنتيجة الخام بديلٌ معلَن حين يغيب النطاق (الطبقة الواسعة، والسجلّ
   التاريخي) — لا صمتٌ ولا صفر.
   ===================================================================== */
function baseDirOf(score, band) {
  if (Number.isFinite(band) && band >= 0 && band <= 4) return band <= 1 ? -1 : 1;
  if (!Number.isFinite(score)) return null;
  return score < DIR_CUT ? -1 : 1;
}

/* =====================================================================
   التعارض الجوهري — شرطٌ يفرض اتجاهاً يعاكس نطاقاً **متطرّفاً**.

   النطاق ‎0‎ «هابط قوي» و‎4‎ «صاعد قوي» حدُّهما ‎∓45‎ — حدود `labelOf`
   نفسها لا عتبةٌ مخترَعة. فحين يقول الشرط «اشترِ» ويقول النطاقُ
   المثبَّت «هابط قوي» فليست هذه مفاضلةً بل قراءتان متناقضتان، وعرضُ
   إحداهما تحت الأخرى يجعل المستخدم يرى «صعود» فوق أربعة فريماتٍ
   هابطة — وهو ما بلّغ عنه فعلاً.

   ولا تُطلق على الميل العادي (نطاق ‎1‎ و‎3‎): الفرض هناك مفاضلةٌ قاسها
   الأرشيف وأيّدها (`vol` ‎−0.72 → −0.34‎)، وإلغاؤه كلَّه يهدم حافّةً
   مقيسة لعلاج حالةٍ متطرّفة.
   ===================================================================== */
function conflictOf(forced, band) {
  if (forced !== 1 && forced !== -1) return false;
  if (!Number.isFinite(band)) return false;
  return (forced === 1 && band === 0) || (forced === -1 && band === 4);
}

/* =====================================================================
   القرار الواحد.

   يعيد `dir` — وهو الاتجاه الذي **يجب** أن تُبنى به الخطة والمستويات
   والأهداف وتُعرض به الفرصة، بلا استثناء — و`conflict` التي تعني
   «لا تُعرض هذه الفرصة أصلاً».

   و`null` حين لا نعرف: «لا اتجاه» ليست «صعود» — وهي القاعدة الموثّقة
   أن حقلاً غيابُه له معنى لا يُفحص بالصدق.
   ===================================================================== */
function resolveDir(o) {
  var score = o && o.score, band = o && o.band, forced = o && o.forced;
  var base = baseDirOf(score, band);
  if (forced !== 1 && forced !== -1) {
    return { dir: base, base: base, forced: null, conflict: false };
  }
  return { dir: forced, base: base, forced: forced, conflict: conflictOf(forced, band) };
}

/* =====================================================================
   قرارُ الرمز كاملاً — اتجاهٌ واحد، وشروطٌ تُقبل أو تُسقَط بمقياسه.

   الدقّة هنا ليست تفصيلاً: `AVGO` تُطلق `alignDn` (▼ سليم، يوافق
   النطاق) و`divBull` (▲ مفروض، يعاكس نطاقاً متطرّفاً) معاً. فحجبُ
   الرمز كلَّه يُضيّع إشارةً هابطة صحيحة، وقبولُه كما هو يعرض فرصتين
   متعاكستين للسهم نفسه. الصحيح: اتجاهُ الرمز من النطاق المثبَّت، ثم
   **يُسقَط الشرط الذي لا يوافقه** — فلا يمكن أن يظهر Call وPut لنفس
   السهم في نفس اللحظة، ولا أن تُبنى أهدافٌ في جهةٍ غير جهة الفرصة.

   `hits` مصفوفة `{ id, forced }` — يمرّرها المستهلك، فلا يستورد هذا
   الملفّ تعريفات الشروط ولا يصير الأرشيف محتاجاً إلى الواجهة.
   ===================================================================== */
function resolveOpp(o) {
  var score = o && o.score, band = o && o.band;
  var hits = (o && o.hits) || [];
  var base = baseDirOf(score, band);
  if (!hits.length) return { dir: null, base: base, kept: [], dropped: [], conflict: false };

  /* الفرض يغلب النطاق **ما لم** يكن النطاق متطرّفاً — وهي نفس مفاضلة
     `planDirOf` مع حدٍّ واحد مضاف: لا فرضَ ضدّ قراءةٍ قاطعة. */
  var forced = null;
  for (var i = 0; i < hits.length; i++) {
    var fd = hits[i] && hits[i].forced;
    if ((fd === 1 || fd === -1) && !conflictOf(fd, band)) { forced = fd; break; }
  }
  var dir = (forced === 1 || forced === -1) ? forced : base;

  /* اتجاهُ الشرط نفسه: المفروض باتجاه فرضه، وغيرُ المفروض باتجاه الرمز.
     فشرطٌ هابط (`dir = −1` في تعريفه) لا يُقبل تحت فرصةٍ صاعدة. */
  var kept = [], dropped = [];
  for (var j = 0; j < hits.length; j++) {
    var h = hits[j], hf = h && h.forced;
    var own = (hf === 1 || hf === -1) ? hf
            : ((h && (h.dir === 1 || h.dir === -1)) ? h.dir : dir);
    (own === dir ? kept : dropped).push(h);
  }
  return { dir: kept.length ? dir : null, base: base,
           kept: kept, dropped: dropped, conflict: !kept.length };
}

if (typeof module !== "undefined" && module.exports) {
  module.exports = { DIR_CUT, baseDirOf, conflictOf, resolveDir, resolveOpp };
}
