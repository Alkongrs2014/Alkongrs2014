/* =====================================================================
   درجة التوافق — رقمٌ واحد موقَّع يصف «كم طريقةً مستقلّة ترى نفس الجهة،
   وبأيّ قوّة». نسخة واحدة يقرأها المتصفح والخادم معاً (نمط `plan.js`
   و`scans.js` و`consensus.js`).

   لماذا ملفٌّ مستقل ولم تُضَف الدوالّ إلى `consensus.js`: هذا الملفّ
   يجيب سؤالين لا يجيبهما الإجماع، وكلاهما يُستهلك في **ثلاثة** مواضع
   مختلفة يجب ألّا تتباعد:

     ١. تحويل الإجماع إلى **درجةٍ موقَّعة** ‎−1..+1‎ ونسبةٍ مئوية —
        يقرؤها ترتيبُ الكون وبطاقةُ الفرصة وقسمُ «توجه السوق».
     ٢. **بناء الإجماع من `strategies.json` المخزَّن** بدل إعادة تقييم
        الاستراتيجيات — وهو ما يجعل هذه الميزة بكلفة صفر طلبات.

   وكان (٢) مكتوباً داخل `rkRows` في الصفحة وحدها. ونسخُه إلى بطاقةٍ
   ثانية وثالثة هو بالضبط ما حذّرت منه قاعدةُ «لا تكرّر منطق
   الاستراتيجيات في عدة أماكن»: الحشوُ بغير المتفعّلة سطرٌ واحد
   ينساه الناسخ فيقول السطر «‎0‎ لم تتفعّل» عن رمزٍ تفعّلت فيه واحدة
   من عشر.

   يُحمَّل في المتصفح كسكربت كلاسيكي، ويُقرأ في Node عبر
   `module.exports`. لا وحدات ES ولا مُجمِّع.
   ===================================================================== */

/* في Node لا تتشارك الملفات نطاقاً عالمياً كما في المتصفح — نفس شيم
   `strategies.js` و`scans.js`. */
if (typeof consensusOf === "undefined" && typeof require === "function") {
  try {
    var _C = require("./consensus.js");
    globalThis.consensusOf = _C.consensusOf;
    globalThis.weightFor = _C.weightFor;
    globalThis.CONF_HI = _C.CONF_HI;
  } catch (e) { /* المتصفح لا يمرّ من هنا أصلاً */ }
}

/* =====================================================================
   الثوابت — ولا واحد منها مخترَع.

   `SCS_FULL` كتلةُ «توافقٍ تامّ» = ثلاث استراتيجيات مقتنعة بوزنٍ
   محايد. وهي ليست ذوقاً: `consensusOf` نفسها تشترط `act.length >= 3`
   للثقة العالية، فالثلاثة هي عتبةُ «إجماعٌ لا رأي» في هذا المشروع
   أصلاً — تُقرأ من هناك ولا تُعاد اختراعاً.

   `SCS_FLOOR` يضبط **كم تُحابى الإشارةُ المنفردة**. وقيمتُه ليست
   ذوقاً: شرطُ الثقة العالية في `consensusOf` هو ‎act.length >= 3‎،
   فالترتيب الذي يجب أن يصمد هو **منفردةٌ < اثنتان < ثلاث**.

   وأوّل قيمةٍ جُرّبت (‎0.6‎) كسرت هذا الترتيب في العرض فعلاً: إشارةٌ
   منفردة مقتنعة تماماً أعطت ‎0.73‎ وخرجت بـ‎+11‎ نقطة، بينما خمسُ
   استراتيجيات بينها خلافٌ يسير أعطت ‎+9‎ — فقرأ الصفّان مقلوبين على
   الشاشة (`SWKS` بواحدة فوق `BRK-B` بخمس). الرقم كان صحيحاً حسابياً
   وكاذباً دلالةً: يقيس **نقاء** الاتفاق ولا يقيس **اتّساعه**.

   وبـ‎0.35‎ يصير: منفردةٌ ‎0.57‎ · اثنتان ‎0.78‎ · ثلاثٌ ‎1.0‎ —
   فيوافق الرقمُ الوسمَ الذي يقوله النظام عن نفسه.

   `SCS_W` وزنُ التوافق في درجة الفرصة: ‎±15‎ نقطة على مئة. **جمعٌ لا
   ضرب** — الضرب يجعل الأثر يتناسب مع الرتبة فيُحابى صدرُ القائمة
   ويكاد لا يمسّ ذيلها، بينما المطلوب إزاحةٌ متساوية للجميع.
   ===================================================================== */
var SCS_FULL = 3;
var SCS_FLOOR = 0.35;
var SCS_W = 0.15;

/* =====================================================================
   حدّا الوسم — **مشتقّان من نسبة الاتفاق لا مكتوبَين**.

   بتغطيةٍ تامّة تصير `pct` هي `|net| × 100`، و`net` دالّةٌ في نسبة
   اتفاق الأغلبية: `net = 2 × agree − 1`. فالحدّان يُقلبان من حدَّي
   الثقة في `consensusOf` بدل اختراع رقمين:

     · «صاعد» يبدأ حيث تقول آلةُ الإجماع نفسها **ثقةٌ عالية**
       (`CONF_HI = 0.78`) ⇒ ‎net = 0.56‎ ⇒ ‎56%‎.
     · «صاعد قوي» عند اتفاقٍ شبه تامّ — مخالفٌ واحد في تسعة
       (`agree = 8/9`) ⇒ ‎net = 0.78‎ ⇒ ‎78%‎.

   وكتابتُهما رقمين حرّين كانت ستجعلهما ينزلقان عن حدود الثقة بأوّل
   تعديلٍ هناك، فيقول الوسمُ «صاعد» حيث يقول الإجماع «ثقةٌ منخفضة».
   والاشتقاق يمنع ذلك بنيوياً. */
var _CONF_HI = (typeof CONF_HI !== "undefined") ? CONF_HI : 0.78;
var DIR_ON = Math.round((2 * _CONF_HI - 1) * 100);
var DIR_STRONG = Math.round((2 * (8 / 9) - 1) * 100);

/* =====================================================================
   من الإجماع إلى درجةٍ موقَّعة.

   والمخرَج **يفرّق بين ثلاثة أصفار** لا يجوز خلطها:

     `scs === null`  لا إشارة أصلاً — «لا نعرف». لا تعديل ولا وسم.
     `scs === 0` مع `mixed`  تعارضٌ مقيس — «نعرف أنّا لا نعرف».
     `scs` صغيرٌ موجب أو سالب  جهةٌ ضعيفة — معلومةٌ ثالثة مختلفة.

   خلطُها يجعل رمزاً بلا بيانات يُقرأ «محايداً» — وهي نفس قاعدة «اعرض
   ‎—‎ لا رقماً ملفّقاً».
   ===================================================================== */
function scsFrom(cons) {
  var out = { scs: null, dir: 0, pct: null, net: null, cover: null,
              n: (cons && cons.n) || 0, mixed: false, conf: (cons && cons.conf) || null };
  if (!cons) return out;
  var up = cons.up || 0, dn = cons.dn || 0, total = up + dn;
  if (!(total > 0)) return out;

  out.net = (up - dn) / total;
  out.cover = Math.min(1, total / SCS_FULL);

  /* التعارض يُفحص قبل الاتجاه — نفس ترتيب `consensusOf`، ولنفس السبب:
     «‎4‎ شراء و‎3‎ بيع» ليست شراءً ضعيفاً. ويُعطى صفراً **موقَّعاً
     معلناً** (`mixed`) لا `null`: الفرق بين «قِيس فخرج متعارضاً» و«لم
     يُقَس» فرقٌ يقرؤه المستخدم. */
  if (cons.k === "mixed") {
    out.scs = 0; out.mixed = true; out.pct = 0;
    return out;
  }
  var str = Math.abs(out.net) * (SCS_FLOOR + (1 - SCS_FLOOR) * out.cover);
  out.dir = out.net > 0 ? 1 : (out.net < 0 ? -1 : 0);
  out.scs = out.dir * str;
  out.pct = Math.round(str * 100);
  return out;
}

/* وسمُ التوجّه من النسبة والجهة. والوسم يتبع النسبة لا العكس، فلا
   يظهر «صاعد قوي ‎40%‎» أبداً. */
function dirLabelOf(dir, pct) {
  if (!dir || !Number.isFinite(pct) || pct < DIR_ON)
    return { k: "flat", t: "محايد", c: "var(--mut)" };
  var up = dir > 0;
  if (pct >= DIR_STRONG)
    return { k: up ? "up2" : "dn2", t: up ? "صاعد قوي" : "هابط قوي",
             c: up ? "var(--up)" : "var(--dn)" };
  return { k: up ? "up" : "dn", t: up ? "صاعد" : "هابط",
           c: up ? "var(--up)" : "var(--dn)" };
}

/* =====================================================================
   أثر التوافق على درجة الفرصة.

   `base` رتبةٌ مئوية ‎0..1‎ (الأفضل ‎1‎) **لا قيمةُ مقياس المسح**:
   `scan.rank` تعيد سعراً في مسحٍ وRSI في آخر ومضاعفَ حجمٍ في ثالث،
   وكلَّها تصاعدياً. فضربُها أو جمعُها بمعاملٍ خلطُ وحدات — بينما
   الرتبة بلا وحدة وتصلح لكل المسوح بصيغةٍ واحدة.

   `sd` اتجاه خطة الفرصة (`planDirOf`). وغيابه يعني أنّا لا نعرف
   بأيّ جهةٍ نقارن، فلا تعديل — لا تعديلٌ بالصفر.
   ===================================================================== */
function oppQualityOf(base, scs, sd) {
  var out = { q: base, adj: 0, align: null, scs: (scs === undefined ? null : scs) };
  if (!Number.isFinite(base)) { out.q = null; return out; }
  if (out.scs === null || (sd !== 1 && sd !== -1)) return out;
  out.align = out.scs * sd;
  out.adj = SCS_W * out.align;
  out.q = Math.max(0, Math.min(1, base + out.adj));
  return out;
}

/* =====================================================================
   بناء الإجماع من `strategies.json` المخزَّن — بلا إعادة تقييم.

   `mine` صفوفُ الرمز الواحد، و`meta` خريطةُ تعريفات الاستراتيجيات
   (`id → {lbl, fam, tf}`)، و`total` عددُها الكلّي.

   **والحشو بغير المتفعّلة ليس تجميلاً**: `consensusOf` تحسب «كم لم
   تتفعّل» من طول المصفوفة، و`strategies.json` لا يحفظ إلا ما تفعّل.
   فبلا الحشو يقول السطر «‎0‎ لم تتفعّل» عن رمزٍ تفعّلت فيه واحدة من
   عشر — ويُقرأ إجماعاً تامّاً.
   ===================================================================== */
function consFromRows(mine, meta, o) {
  o = o || {};
  var M = meta || {}, total = o.total || 0;
  var res = (mine || []).map(function (r) {
    var m = M[r.st] || {};
    return { id: r.st, lbl: m.lbl || r.st, fam: m.fam || "trend", tf: m.tf || null,
             dir: r.dir, sc: r.sc, band: r.band, active: !!r.act, at: r.at, px0: r.px0 };
  });
  var pad = Math.max(0, total - res.length);
  for (var i = 0; i < pad; i++) res.push({ id: "_q" + i, dir: 0, sc: null, active: false });
  return { res: res, cons: consensusOf(res, o) };
}

/* أقدمُ إشارةٍ نشطة — «منذ متى؟» تُقاس بأوّل ما بدأ لا بآخره. `at`
   بالثواني في الملفّ المخزَّن. */
function oldestActiveAt(res) {
  var ts = (res || []).filter(function (r) { return r.active && r.dir && r.at; })
                      .map(function (r) { return r.at; });
  return ts.length ? Math.min.apply(null, ts) * 1000 : null;
}

if (typeof module !== "undefined" && module.exports) {
  module.exports = {
    SCS_FULL: SCS_FULL, SCS_FLOOR: SCS_FLOOR, SCS_W: SCS_W,
    DIR_STRONG: DIR_STRONG, DIR_ON: DIR_ON,
    scsFrom: scsFrom, dirLabelOf: dirLabelOf, oppQualityOf: oppQualityOf,
    consFromRows: consFromRows, oldestActiveAt: oldestActiveAt
  };
}
