#!/usr/bin/env node
/* =====================================================================
   فحص الزمن والجلسة — بلا شبكة.

   لماذا فحصٌ مستقلّ بهذا الحجم لملفٍّ صغير: كلُّ خللٍ زمنيّ في هذا
   المشروع كان **صامتاً**. لا استثناء ولا رقم خارج المدى — فقط أرقامٌ
   صحيحة تصف لحظةً أخرى. «الفترات المحفوظة تصف يوم جلبها» كلّفت 487
   رمزاً على شمعة أمس طوال جلسة، و«صلاحية ‎20‎ ساعة لا تقسم ‎24‎»
   أزاحت وقت الجلب أربع ساعات كل يوم بلا نمطٍ ظاهر. وكلاهما مرّ من
   تشغيلاتٍ ناجحة.

     node scripts/check-session.mjs
   ===================================================================== */
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const S = require(path.join(ROOT, "stocks/session.js"));

let pass = 0, fail = 0;
const t = (n, fn) => {
  try { fn(); console.log(`  ✓ ${n}`); pass++; }
  catch (e) { console.log(`  ✗ ${n} — ${e.message}`); fail++; }
};
const eq = (a, b, m) => {
  if (JSON.stringify(a) !== JSON.stringify(b))
    throw new Error(`${m}: ${JSON.stringify(a)} ≠ ${JSON.stringify(b)}`);
};
const U = (s) => Date.parse(s);
const iso = (t) => new Date(t).toISOString();

console.log("\n▶ فحص الزمن والجلسة\n");

/* ---------------------------------------------------------------------
   ١) المرساة — الحدث لا رقم الساعة
   --------------------------------------------------------------------- */
t("مرساة البدء ‎04:00‎ نيويورك: ‎08:00 UTC‎ صيفاً و‎09:00 UTC‎ شتاءً", () => {
  eq(iso(S.scanStartOf(U("2026-07-15T12:00:00Z"))), "2026-07-15T08:00:00.000Z", "صيفاً");
  eq(iso(S.scanStartOf(U("2026-12-15T12:00:00Z"))), "2026-12-15T09:00:00.000Z", "شتاءً");
});

t("ونفس اللحظة تُعرض ‎11:00‎ صيفاً و‎12:00‎ شتاءً بالرياض", () => {
  eq(S.ksaTime(S.scanStartOf(U("2026-07-15T12:00:00Z"))), "11:00", "صيفاً");
  eq(S.ksaTime(S.scanStartOf(U("2026-12-15T12:00:00Z"))), "12:00", "شتاءً");
});

t("‎11:00‎ الرياض شتاءً = ‎03:00‎ نيويورك — قبل أن توجد بيانات (سببُ رفض الرقم الثابت)", () => {
  // 11:00 الرياض = 08:00 UTC. في ديسمبر نيويورك UTC-5 ⇒ 03:00
  const p = S.etParts(U("2026-12-15T08:00:00Z"));
  eq(p.h, 3, "ساعة نيويورك");
  eq(S.sessionOf(U("2026-12-15T08:00:00Z")), "CLOSED", "الحالة");
});

/* ---------------------------------------------------------------------
   ٢) حدود الجلسات بالدقيقة — الحدُّ نفسه لا ما حوله
   --------------------------------------------------------------------- */
t("حدود الجلسات الأربع بالدقيقة (يوم تداول عادي، توقيت صيفي)", () => {
  const at = (hhmm) => U(`2026-09-15T${hhmm}:00Z`);
  // 2026-09-15 ثلاثاء، EDT ⇒ ET = UTC-4
  eq(S.sessionOf(at("07:59")), "CLOSED",  "03:59 ET");
  eq(S.sessionOf(at("08:00")), "PRE",     "04:00 ET");
  eq(S.sessionOf(at("13:29")), "PRE",     "09:29 ET");
  eq(S.sessionOf(at("13:30")), "REGULAR", "09:30 ET");
  eq(S.sessionOf(at("19:59")), "REGULAR", "15:59 ET");
  eq(S.sessionOf(at("20:00")), "AFTER",   "16:00 ET");
  eq(S.sessionOf(at("23:59")), "AFTER",   "19:59 ET");
  eq(S.sessionOf(U("2026-09-16T00:00:00Z")), "CLOSED", "20:00 ET");
});

t("وبالتوقيت الشتوي تنزاح كلُّها ساعةً ولا تتغيّر أسماؤها", () => {
  const at = (hhmm) => U(`2026-12-15T${hhmm}:00Z`);   // EST ⇒ ET = UTC-5
  eq(S.sessionOf(at("08:59")), "CLOSED",  "03:59 ET");
  eq(S.sessionOf(at("09:00")), "PRE",     "04:00 ET");
  eq(S.sessionOf(at("14:30")), "REGULAR", "09:30 ET");
  eq(S.sessionOf(at("21:00")), "AFTER",   "16:00 ET");
});

/* ---------------------------------------------------------------------
   ٣) يوما الانتقال — الساعة المفقودة والساعة المكرّرة
   --------------------------------------------------------------------- */
t("‎2026-03-08‎ (تقديم الساعة): ‎02:00‎ لا وجود لها ومرساةُ اليوم تبقى ‎04:00 ET‎", () => {
  const day = U("2026-03-08T18:00:00Z");
  /* ‎04:00 ET‎ تقع **بعد** لحظة التقديم (‎02:00‎)، فاليومُ نفسه صيفيّ
     ⇒ ‎08:00 UTC‎. وحدسُ «يومُ الانتقال نصفُه هنا ونصفُه هناك» يخطئ
     هنا بالضبط — وقعتُ فيه وأسقطه هذا الفحص. */
  eq(iso(S.scanStartOf(day)), "2026-03-08T08:00:00.000Z", "المرساة");
  // الأحد ليس يوم تداول — والمرساة تُحسب مع ذلك لأنها دالّة تقويم لا قرار
  eq(S.isTradingDay(day), false, "الأحد");
  // الساعة المفقودة: 02:30 ET لا وجود لها، والدالّة يجب ألّا تدور
  const got = S.etParts(S.atEtMinutes(day, 150));
  if (!Number.isFinite(got.mins)) throw new Error("ساعة مفقودة كسرت الحساب");
});

t("‎2026-11-01‎ (تأخير الساعة): الساعة المكرّرة لا تكسر النوافذ", () => {
  const day = U("2026-11-01T18:00:00Z");
  /* وكذلك التأخير: ‎04:00 ET‎ بعد لحظة الرجوع فاليومُ شتويّ ⇒ ‎09:00 UTC‎ */
  eq(iso(S.scanStartOf(day)), "2026-11-01T09:00:00.000Z", "المرساة بعد الانتقال");
  const mon = U("2026-11-02T18:00:00Z");
  eq(iso(S.scanStartOf(mon)), "2026-11-02T09:00:00.000Z", "الاثنين بعده");
});

t("الانتقال يقع بين جمعةٍ واثنين فتتغيّر المرساة ساعةً بين يومَي تداول", () => {
  const fri = S.scanStartOf(U("2026-10-30T18:00:00Z"));
  const mon = S.scanStartOf(U("2026-11-02T18:00:00Z"));
  eq(S.ksaTime(fri), "11:00", "الجمعة");
  eq(S.ksaTime(mon), "12:00", "الاثنين");
});

t("`atEtMinutes` تعيد اللحظة التي أجزاؤها هي المطلوبة — على مدار اليوم وفي يومَي الانتقال", () => {
  for (const d of ["2026-03-06", "2026-03-08", "2026-03-09", "2026-11-01", "2026-11-02", "2026-06-20"]) {
    const base = U(`${d}T18:00:00Z`);
    for (let m = 0; m < 1440; m += 7) {
      const p = S.etParts(base);
      const q = S.etParts(S.atEtMinutes(base, m));
      // الساعة المفقودة (02:00–03:00 يوم التقديم) لا نظير لها — تُستثنى
      if (d === "2026-03-08" && m >= 120 && m < 180) continue;
      if (q.mins !== m || q.date !== p.date)
        throw new Error(`${d} ${m}د ⇒ ${q.date} ${q.mins}د`);
    }
  }
});

/* ---------------------------------------------------------------------
   ٤) العطلات وأنصاف الأيام
   --------------------------------------------------------------------- */
t("عطلة رسمية ليست يوم تداول ولو كانت وسط الأسبوع", () => {
  eq(S.sessionOf(U("2026-12-25T15:00:00Z")), "CLOSED", "الميلاد (جمعة)");
  eq(S.sessionOf(U("2026-07-03T15:00:00Z")), "CLOSED", "عطلة الاستقلال المنقولة");
  eq(S.sessionOf(U("2026-11-26T15:00:00Z")), "CLOSED", "الشكر");
});

t("عطلة نهاية الأسبوع مغلقة في كل الساعات", () => {
  eq(S.sessionOf(U("2026-09-12T15:00:00Z")), "CLOSED", "السبت");
  eq(S.sessionOf(U("2026-09-13T15:00:00Z")), "CLOSED", "الأحد");
});

t("نصفُ اليوم يُغلق ‎13:00‎ لا ‎16:00‎ — وإلا قُرئت ثلاث ساعاتٍ ممتدة جلسةً رسمية", () => {
  const at = (hhmm) => U(`2026-11-27T${hhmm}:00Z`);   // ما بعد الشكر، EST ⇒ UTC-5
  eq(S.isHalfDay(S.etParts(at("15:00"))), true, "موسوم نصفَ يوم");
  eq(S.sessionOf(at("17:59")), "REGULAR", "12:59 ET");
  eq(S.sessionOf(at("18:00")), "AFTER",   "13:00 ET");
  eq(S.sessionOf(at("21:59")), "AFTER",   "16:59 ET");
  eq(S.sessionOf(at("22:00")), "CLOSED",  "17:00 ET");
});

t("والكريبتو خارج هذا كلّه: مفتوحٌ ليل السبت وفي الميلاد", () => {
  eq(S.sessionOf(U("2026-09-12T03:00:00Z"), "crypto"), "OPEN24", "السبت");
  eq(S.sessionOf(U("2026-12-25T15:00:00Z"), "crypto"), "OPEN24", "الميلاد");
  eq(S.isExtendedOpen(U("2026-09-13T22:00:00Z"), "crypto"), true, "الأحد ليلاً");
});

/* ---------------------------------------------------------------------
   ٥) النوافذ ودقيقة الجلسة
   --------------------------------------------------------------------- */
t("النوافذ متّصلة ولا تتداخل: نهايةُ كلٍّ بدايةُ ما بعدها", () => {
  const w = S.sessionWindows(U("2026-09-15T15:00:00Z"));
  eq(w.pre.end, w.regular.start, "قبل ⇄ رسمية");
  eq(w.regular.end, w.post.start, "رسمية ⇄ بعد");
  eq((w.regular.end - w.regular.start) / 3600000, 6.5, "طول الجلسة الرسمية");
  eq((w.pre.end - w.pre.start) / 3600000, 5.5, "طول ما قبل الافتتاح");
});

t("`currentWindow` تتبع الجلسة الجارية لا الرسمية دائماً", () => {
  const pre = U("2026-09-15T10:00:00Z");     // 06:00 ET
  const reg = U("2026-09-15T15:00:00Z");     // 11:00 ET
  const aft = U("2026-09-15T21:00:00Z");     // 17:00 ET
  eq(iso(S.currentWindow(pre).start), "2026-09-15T08:00:00.000Z", "ما قبل");
  eq(iso(S.currentWindow(reg).start), "2026-09-15T13:30:00.000Z", "الرسمية");
  eq(iso(S.currentWindow(aft).start), "2026-09-15T20:00:00.000Z", "ما بعد");
  eq(S.currentWindow(U("2026-09-15T03:00:00Z")), null, "خارج الجلسات");
});

t("`minuteOfSession` تُقاس من بداية الجلسة الجارية — أساسُ خطّ الحجم", () => {
  eq(S.minuteOfSession(U("2026-09-15T08:00:00Z")), 0,   "أول دقيقة قبل الافتتاح");
  eq(S.minuteOfSession(U("2026-09-15T10:10:00Z")), 130, "06:10 ET");
  eq(S.minuteOfSession(U("2026-09-15T13:30:00Z")), 0,   "أول دقيقة رسمية");
});

/* ---------------------------------------------------------------------
   ٦) الحالة والعدّاد
   --------------------------------------------------------------------- */
t("`statusAt` تعطي الحدث التالي الصحيح لكل جلسة", () => {
  eq(S.statusAt(U("2026-09-15T10:00:00Z")).nextAr, "يفتتح بعد", "قبل الافتتاح");
  eq(iso(S.statusAt(U("2026-09-15T10:00:00Z")).next), "2026-09-15T13:30:00.000Z", "لحظة الافتتاح");
  eq(S.statusAt(U("2026-09-15T15:00:00Z")).nextAr, "يغلق بعد", "الجلسة");
  eq(S.statusAt(U("2026-09-15T21:00:00Z")).nextAr, "تنتهي الجلسة بعد", "بعد الإغلاق");
});

t("والمغلقُ عدّادُه إلى بدء الماسح التالي — يتخطّى العطلة ونهاية الأسبوع", () => {
  // جمعة 2026-09-11 بعد نهاية الجلسة الممتدة ⇒ التالي اثنين 09-14
  eq(iso(S.nextScanStart(U("2026-09-12T01:00:00Z"))), "2026-09-14T08:00:00.000Z", "بعد الجمعة");
  // أربعاء 2026-11-25 ليلاً ⇒ الخميس عطلة الشكر ⇒ التالي الجمعة 11-27
  eq(iso(S.nextScanStart(U("2026-11-26T02:00:00Z"))), "2026-11-27T09:00:00.000Z", "يتخطّى الشكر");
});

t("`scannerActive` صادقةٌ في الجلسات الثلاث وكاذبةٌ خارجها", () => {
  eq(S.scannerActive(U("2026-09-15T10:00:00Z")), true,  "ما قبل الافتتاح");
  eq(S.scannerActive(U("2026-09-15T15:00:00Z")), true,  "الجلسة");
  eq(S.scannerActive(U("2026-09-15T21:00:00Z")), true,  "بعد الإغلاق");
  eq(S.scannerActive(U("2026-09-15T02:00:00Z")), false, "الليل");
  eq(S.scannerActive(U("2026-09-12T15:00:00Z")), false, "السبت");
});

/* ---------------------------------------------------------------------
   ٧) وسمُ الشمعات — ما يفصل الرسمية عن الممتدة
   --------------------------------------------------------------------- */
t("وسمُ الشمعة يفصل الممتدة عن الرسمية بلا حقلٍ مخزَّن", () => {
  eq(S.isExtendedBar(U("2026-09-15T10:00:00Z")), true,  "06:00 ET");
  eq(S.isExtendedBar(U("2026-09-15T15:00:00Z")), false, "11:00 ET");
  eq(S.isRegularBar(U("2026-09-15T15:00:00Z")), true,   "11:00 ET");
  eq(S.isRegularBar(U("2026-09-15T21:00:00Z")), false,  "17:00 ET");
  // الكريبتو كلُّه «رسميّ»: لا جلسة ممتدة لسوقٍ لا يغلق
  eq(S.isRegularBar(U("2026-09-12T03:00:00Z"), "crypto"), true, "كريبتو");
  eq(S.isExtendedBar(U("2026-09-12T03:00:00Z"), "crypto"), false, "كريبتو ممتد");
});

/* ---------------------------------------------------------------------
   ٨) الجدولُ يتقادم — والفحص يقول ذلك قبل أن يقوله السوق
   --------------------------------------------------------------------- */
t("جدول العطلات يغطّي السنة القادمة على الأقل", () => {
  const years = Object.keys(S.HOLIDAYS).map(Number).sort((a, b) => a - b);
  const last = years[years.length - 1];
  const thisYear = new Date().getUTCFullYear();
  if (last < thisYear + 1)
    throw new Error(`آخر سنة مغطّاة ${last} والسنة ${thisYear} — مدّد HOLIDAYS و HALF_DAYS في stocks/session.js`);
  for (const y of years) {
    if ((S.HOLIDAYS[y] || []).length < 9)
      throw new Error(`عطلات ${y} ناقصة (${(S.HOLIDAYS[y] || []).length}) — التقويم الأمريكي تسعُ عطلاتٍ فأكثر`);
  }
});

/* ---------------------------------------------------------------------
   ٩) لا نسخة ثانية من هذا المنطق
   --------------------------------------------------------------------- */
t("العرضُ بتوقيت الرياض صراحةً لا بمنطقة المتصفّح", () => {
  const t0 = U("2026-09-15T08:00:00Z");
  eq(S.ksaTime(t0), "11:00", "الوقت");
  // أرقامٌ لاتينية لا هندية: بقيّة الواجهة أرقامُها لاتينية، واختلافُها
  // في خانةٍ واحدة يُقرأ عطلاً
  if (/[٠-٩]/.test(S.ksaTime(t0))) throw new Error("أرقام هندية في وقت الرياض");
});

console.log(`\n${fail ? "✗" : "✔"} ${pass} نجحت · ${fail} فشلت\n`);
process.exit(fail ? 1 : 0);
